import numpy as np

# ====================== 1. 准备数据（对应：桌子上摆红/绿苹果） ======================
# 核心原理：把现实中的苹果位置/类别，转成电脑能懂的数字
# X：6个苹果的位置（单位：厘米），红苹果[1,3,5]，绿苹果[7,9,11]
X = np.array([1, 3, 5, 7, 9, 11])
# y：苹果的类别标签（红苹果=1，绿苹果=-1），用来告诉电脑“正确答案”
y = np.array([1, 1, 1, -1, -1, -1])


# ====================== 2. 定义损失计算函数（对应：给当前直线打“差评”） ======================
def calculate_loss(W, b, X, y):
    """
    核心作用：计算当前直线的“差评分数”（损失）→ 分数越高，直线越差
    参数说明：
    - W：直线的斜率（这里固定为1，因为是桌子上的横线，只调位置不调倾斜）
    - b：直线的位置参数（直线方程：W*x + b = 0 → x = -b，比如b=-6时直线在6厘米处）
    - X：所有苹果的位置
    - y：所有苹果的正确类别（红=1，绿=-1）
    """
    loss = 0.0  # 初始化总损失为0（还没给直线打分）
    delta = 1   # SVM的“安全间隔”：要求正确类苹果离直线至少1厘米，否则扣分

    # 遍历每个苹果，逐个打分
    for i in range(len(X)):
        # 步骤1：算当前苹果的“得分”→ 电脑判断这个苹果属于哪一类
        # 原理：一维直线的得分公式，得分符号代表类别（红=正，绿=负），绝对值代表离直线的距离
        score = W * X[i] + b

        # 步骤2：计算标准合页损失的margin（核心修正！）
        # 标准合页损失公式：max(0, 1 - y[i] * score)
        # 原理：
        # - y[i]*score > 1 → 分对且离直线≥1厘米 → margin=0 → 不扣分
        # - 0 < y[i]*score ≤1 → 分对但离得太近 → margin>0 → 扣少量分
        # - y[i]*score ≤0 → 分错了 → margin≥1 → 扣大量分
        margin = max(0, delta - y[i] * score)

        # 步骤3：累加差评（合页损失核心：只累加正的margin）
        loss += margin

    # 返回平均损失：所有苹果的差评平均分（避免苹果数量影响打分）
    return loss / len(X)


# ====================== 3. 定义梯度下降函数（对应：手动挪直线找最优位置） ======================
def gradient_descent(X, y, init_b, learning_rate, num_iters):
    """
    核心作用：模拟“手动挪直线”的过程→ 每次挪一小步，直到找到损失最小的位置
    参数说明（大白话）：
    - init_b：直线的初始位置参数（比如-6→直线在6厘米处）
    - learning_rate：步长→ 每次挪多远（比如0.1=每次挪0.1厘米）
    - num_iters：挪多少次→ 试错的次数
    """
    W = 1  # 斜率固定为1（只调位置，不调倾斜）
    b = init_b  # 初始直线位置（比如-6→6厘米处）
    loss_history = []  # 记录每次挪线后的损失→ 看损失是不是越来越小

    # 开始循环挪线（试错num_iters次）
    for i in range(num_iters):
        # 步骤1：算当前直线的损失（给当前位置打差评）
        loss = calculate_loss(W, b, X, y)
        loss_history.append(loss)  # 记录差评，方便后续看变化

        # 步骤2：算梯度（核心！判断“往哪挪、挪多大力”，适配合页损失）
        # 原理：梯度=苹果们的“集体喊话”→ 告诉电脑该往左/右挪，挪多快
        grad_b = 0.0  # 初始化梯度为0（还没听苹果们的意见）
        delta = 1  # 安全间隔（和损失计算一致）

        # 遍历每个苹果，收集“喊话”
        for j in range(len(X)):
            score = W * X[j] + b
            # 只有当margin>0时（苹果有差评），才会产生梯度贡献
            if delta - y[j] * score > 0:
                # 合页损失的梯度公式：-y[j] * W（仅当margin>0时）
                grad_b += -y[j] * W

        # 步骤3：挪直线（梯度下降核心操作）
        # 原理：b = b - 步长*平均梯度 → 往损失变小的方向挪一小步
        # 除以len(X)：平均所有苹果的“喊话”，避免个别苹果喊太响
        b -= learning_rate * grad_b / len(X)

        # 步骤4：打印过程（每10次打印一次，看挪线效果）
        if i % 10 == 0:
            current_line_pos = -b  # 把b转成直观的直线位置（厘米）
            print(f"第{i}次挪线：直线在{current_line_pos:.2f}厘米处，平均损失={loss:.2f}")

    # 返回最优位置和损失变化
    return b, loss_history


# ====================== 4. 运行模拟（对应：开始手动挪直线） ======================
# 初始直线位置：6厘米（对应b=-6，因为x=-b）
init_b = -6
# 步长：每次挪0.1厘米（步长太小挪得慢，太大容易跨过最优位置）
learning_rate = 0.1
# 挪线次数：50次（试50次足够找到最优位置）
num_iters = 50

# 开始挪线！
best_b, loss_history = gradient_descent(X, y, init_b, learning_rate, num_iters)

# ====================== 5. 可视化损失变化（对应：看差评是不是越来越少） ======================
import matplotlib.pyplot as plt
plt.rcParams['font.sans-serif'] = ['SimHei']  # 支持中文
plt.rcParams['axes.unicode_minus'] = False   # 支持负号

# 画损失变化曲线：横轴=挪线次数，纵轴=平均损失
plt.plot(loss_history)
plt.xlabel("挪线次数（试错次数）")
plt.ylabel("平均损失（差评分数）")
plt.title("挪线过程中损失的变化→ 损失越低，直线越好")
plt.show()

# 输出最终结果（转成直观的厘米数）
best_line_pos = -best_b  # 把b转成直线位置
print(f"\n✅ 最优直线位置：{best_line_pos:.2f}厘米（5和7厘米的正中间，间隔最大）")
print(f"✅ 最终平均损失：{loss_history[-1]:.2f}（损失最小，直线最好）")